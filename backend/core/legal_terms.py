"""일상어 → 법령 개념 — 검색 질의 보강과 개념 검색

직원은 "CCTV", "보여줘도 되나요"처럼 일상어로 묻지만 법령 원문은
"고정형 영상정보처리기기", "개인정보의 열람"처럼 법률 용어를 쓴다.
임베딩·BM25 검색 모두 이 간극 때문에 핵심 조문을 놓친다.

두 가지로 사용한다.
1. expand_legal_terms: 검색 질의 뒤에 법령 개념을 덧붙인다
2. concept_queries: 법령 개념만으로 따로 검색한다 — 질문의 지배적인 단어(예: CCTV)에 가려
   두 번째 쟁점(예: 정보주체의 열람권)이 검색되지 않는 문제를 막는다.
   개념은 짧을수록 정확하다 (여러 개념을 한 문장에 섞으면 다시 흐려진다).
"""

from __future__ import annotations

# 일상어(부분 일치) → 법령 개념 목록 (각 개념은 짧게)
LEGAL_TERM_EXPANSIONS: dict[str, list[str]] = {
    "CCTV": ["고정형 영상정보처리기기"],
    "cctv": ["고정형 영상정보처리기기"],
    "씨씨티비": ["고정형 영상정보처리기기"],
    "블랙박스": ["이동형 영상정보처리기기"],
    "드론": ["이동형 영상정보처리기기"],
    "주민번호": ["주민등록번호 처리의 제한", "고유식별정보의 처리 제한"],
    "주민등록번호": ["주민등록번호 처리의 제한", "고유식별정보의 처리 제한"],
    "유출": ["개인정보 유출 등의 통지·신고"],
    "해킹": ["개인정보 유출 등의 통지·신고", "안전조치의무"],
    "외주": ["업무위탁에 따른 개인정보의 처리 제한"],
    "하청": ["업무위탁에 따른 개인정보의 처리 제한"],
    "위탁": ["업무위탁에 따른 개인정보의 처리 제한"],
    "해외 서버": ["개인정보의 국외 이전"],
    "클라우드": ["개인정보의 국외 이전"],
    "마케팅": ["개인정보의 목적 외 이용·제공 제한"],
    "문자 광고": ["영리목적의 광고성 정보 전송 제한"],
    "층간소음": ["층간소음의 방지"],
    "하자": ["하자담보책임", "하자보수"],
    "관리소장": ["관리사무소장의 업무"],
    "동대표": ["동별 대표자", "입주자대표회의의 구성"],
    "위약금": ["손해배상액의 예정"],
    # 개인정보 열람·제공 요청 — 정보주체 열람권과 제3자 제공 제한 조문으로 연결
    "보여달라": ["개인정보의 열람", "개인정보의 제3자 제공"],
    "보여줘도": ["개인정보의 열람", "개인정보의 제3자 제공"],
    "열람": ["개인정보의 열람"],
    "넘겨줘도": ["개인정보의 제3자 제공"],
}

_MAX_CONCEPTS = 4


def concept_queries(query: str) -> list[str]:
    """질의에 포함된 일상어에 대응하는 법령 개념 목록 (중복 제외, 질의에 이미 있는 개념 제외)."""
    concepts: list[str] = []
    for colloquial, legal_list in LEGAL_TERM_EXPANSIONS.items():
        if colloquial not in query:
            continue
        for concept in legal_list:
            if concept not in query and concept not in concepts:
                concepts.append(concept)
    return concepts[:_MAX_CONCEPTS]


def expand_legal_terms(query: str) -> str:
    """질의 뒤에 법령 개념을 덧붙인다."""
    concepts = concept_queries(query)
    return f"{query} {' '.join(concepts)}" if concepts else query
